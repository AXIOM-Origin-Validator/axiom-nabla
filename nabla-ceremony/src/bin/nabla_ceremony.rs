// AXIOM Nabla — Ceremony Binary
//
// Generates real NBCs (Nabla Birth Certificates).
//
// Two modes:
//   Single-node (production):
//     nabla-ceremony --config ~/.axiom/node.toml --root-keys /path/to/root-keys/
//
//   Batch/dev (sim testing):
//     nabla-ceremony --dev --base-dir /path/to/AXIOM_DATA_DIR --count 50

use std::path::PathBuf;

fn main() {
    let args: Vec<String> = std::env::args().collect();

    let mut config_path: Option<PathBuf> = None;
    let mut root_keys_dir: Option<PathBuf> = None;
    let mut dev_mode = false;
    let mut base_dir: Option<PathBuf> = None;
    let mut count: usize = 50;

    let mut i = 1;
    while i < args.len() {
        match args[i].as_str() {
            "--config" | "-c" => {
                i += 1;
                if i < args.len() {
                    config_path = Some(PathBuf::from(&args[i]));
                }
            }
            "--root-keys" | "-r" => {
                i += 1;
                if i < args.len() {
                    root_keys_dir = Some(PathBuf::from(&args[i]));
                }
            }
            "--dev" => {
                dev_mode = true;
            }
            "--base-dir" | "--base" | "-d" => {
                i += 1;
                if i < args.len() {
                    base_dir = Some(PathBuf::from(&args[i]));
                }
            }
            "--count" | "-n" => {
                i += 1;
                if i < args.len() {
                    count = args[i].parse().unwrap_or(50);
                }
            }
            "--help" | "-h" => {
                print_usage();
                std::process::exit(0);
            }
            _ => {
                eprintln!("Unknown argument: {}", args[i]);
                eprintln!();
                print_usage();
                std::process::exit(1);
            }
        }
        i += 1;
    }

    // Validate mutual exclusivity
    if config_path.is_some() && dev_mode {
        eprintln!("ERROR: --config and --dev are mutually exclusive");
        eprintln!();
        print_usage();
        std::process::exit(1);
    }

    if let Some(toml_path) = config_path {
        // ── Single-node mode ──
        if !toml_path.exists() {
            eprintln!("ERROR: Config file does not exist: {}", toml_path.display());
            std::process::exit(1);
        }

        let rk_dir = match root_keys_dir {
            Some(d) => d,
            None => {
                eprintln!("ERROR: --root-keys required in single-node mode");
                eprintln!();
                eprintln!("  Root authority keys are generated by the genesis ceremony (dev.sh → 28n).");
                eprintln!("  Every node must use the SAME root keys so NBCs are mutually trusted.");
                eprintln!();
                print_usage();
                std::process::exit(1);
            }
        };

        if !rk_dir.exists() {
            eprintln!("ERROR: Root keys directory does not exist: {}", rk_dir.display());
            eprintln!();
            eprintln!("  Run the genesis ceremony first (dev.sh → 28n), then copy root-keys/ here.");
            std::process::exit(1);
        }

        match axiom_nabla_ceremony::nabla_ceremony_single(&toml_path, &rk_dir) {
            Ok(node) => {
                eprintln!();
                eprintln!("✓ NBC generated for '{}'", node.nbc.node_name);
            }
            Err(e) => {
                eprintln!("ERROR: {}", e);
                std::process::exit(1);
            }
        }
    } else if dev_mode {
        // ── Batch/dev mode ──
        let base_dir = match base_dir {
            Some(d) => d,
            None => {
                eprintln!("ERROR: --dev requires --base-dir");
                eprintln!();
                print_usage();
                std::process::exit(1);
            }
        };

        if !base_dir.exists() {
            eprintln!("ERROR: Base directory does not exist: {}", base_dir.display());
            std::process::exit(1);
        }

        if count < 10 {
            eprintln!("ERROR: count must be at least 10 (genesis nodes)");
            std::process::exit(1);
        }

        // Verify genesis dirs exist (should have been created by install_genesis.sh)
        let first_genesis = base_dir.join("axiom-first-penguin-alpha");
        if !first_genesis.exists() {
            eprintln!("WARNING: {} does not exist", first_genesis.display());
            eprintln!("         Genesis validator directories should be created first (dev.sh → 27)");
            eprintln!("         Continuing anyway — directories will be created...");
        }

        let nodes = axiom_nabla_ceremony::nabla_ceremony(count, &base_dir);

        eprintln!();
        eprintln!("✓ {} NBCs generated and written to disk.", nodes.len());
        eprintln!("  Sim can now load these with: nabla-sim --base-dir {}", base_dir.display());
    } else {
        // No mode specified
        eprintln!("ERROR: Specify --config <path> for single-node or --dev for batch mode");
        eprintln!();
        print_usage();
        std::process::exit(1);
    }
}

fn print_usage() {
    eprintln!("Usage:");
    eprintln!("  nabla-ceremony --config <node.toml> --root-keys <dir>   Single-node (production)");
    eprintln!("  nabla-ceremony --dev --base-dir <DIR> [--count <N>]     Batch mode (dev/sim)");
    eprintln!();
    eprintln!("Single-node mode:");
    eprintln!("  --config <path>      Path to node.toml (name + port)");
    eprintln!("  --root-keys <dir>    Path to shared root authority keys (required)");
    eprintln!("                       Contains root_{{1,2,3}}.{{pub,key}} from genesis ceremony");
    eprintln!();
    eprintln!("Batch/dev mode:");
    eprintln!("  --dev                Enable batch mode (generates its own root keys)");
    eprintln!("  --base-dir <path>    Path to AXIOM_DATA_DIR");
    eprintln!("  --count <N>          Total nodes including 10 genesis (default: 50)");
    eprintln!();
    eprintln!("Generates Nabla NBCs with separate keypairs from Validator's VBCs.");
}
